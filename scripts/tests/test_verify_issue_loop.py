class TestMergedSkillModeDispatch:
    """Tests that the merged skill documents `mode` correctly and does not
    flatten the two modes' distinct budget values."""

    def test_skill_md_exists(self) -> None:
        assert SKILL_MD.exists(), f"{SKILL_MD} must exist (merged skill, ENH-2881)"

    def test_adversarial_verify_loop_skill_removed(self) -> None:
        old_dir = SKILL_MD.parent.parent / "adversarial-verify-loop"
        assert not old_dir.exists(), (
            "skills/adversarial-verify-loop/ must be fully removed after the ENH-2881 merge"
        )

