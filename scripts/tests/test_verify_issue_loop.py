        criteria_loop = yaml.safe_load(VERIFY_YAML_3_CRITERIA)
        adversarial_loop = yaml.safe_load(ADVERSARIAL_YAML)
        assert criteria_loop["timeout"] == 1800
        assert adversarial_loop["timeout"] == 2700
        assert criteria_loop["timeout"] != adversarial_loop["timeout"]

