        criteria_loop = yaml.safe_load(VERIFY_YAML_3_CRITERIA)
        adversarial_loop = yaml.safe_load(ADVERSARIAL_YAML)
        assert criteria_loop["max_iterations"] == 20
        assert adversarial_loop["max_iterations"] == 20

