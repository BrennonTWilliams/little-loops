        adversarial_loop = yaml.safe_load(ADVERSARIAL_YAML)
        assert criteria_loop["states"]["verify-criterion-1"]["timeout"] == 300
        assert adversarial_loop["states"]["probe-boundary"]["timeout"] == 300

