"""ll-loop scaffold-eval: generate FSM eval-harness loop YAML from issue IDs (FEAT-2948).

Mechanical port of skills/create-eval-from-issues/SKILL.md's Variant A (1 issue)
and Variant B (2+ issues) YAML templates (L265-422), including the Proof-First
Gates `check_proof_<slug>` chaining/splicing logic (L306-327/406-422). Unlike
scaffold-verify, the `execute`/`check_skill` prompt text genuinely requires an
LLM to synthesize (a user-experience narrative and evaluation criteria drawn
from Expected Behavior/Use Case/Acceptance Criteria) — this module only emits
the state graph with `<EXECUTE_PROMPT>`/`<EVALUATION_CRITERIA>` placeholder
slots for that text; proof-state chaining, slug generation, and variant
selection are generated, not narrated.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from little_loops.cli.loop._scaffold_core import ScaffoldResult, dump_fsm_yaml, resolve_issue
from little_loops.cli.output import print_json
from little_loops.file_utils import atomic_write
from little_loops.fsm.schema import EvaluateConfig, FSMLoop, StateConfig
from little_loops.fsm.validation import ValidationSeverity, validate_fsm
from little_loops.issue_parser import IssueInfo, slugify

_VARIANT_A_TIMEOUT = 1800
_VARIANT_B_TIMEOUT = 7200
_VARIANT_A_MAX_STEPS = 5
_VARIANT_B_MAX_STEPS = 50

_EXECUTE_PLACEHOLDER = "<EXECUTE_PROMPT>"
_CRITERIA_PLACEHOLDER = "<EVALUATION_CRITERIA_PROMPT>"


def _learning_tests_enabled() -> bool:
    from little_loops.config import BRConfig

    return bool(BRConfig(Path.cwd()).learning_tests.enabled)


def _proof_state_name(target: str) -> str:
    return f"check_proof_{slugify(target)}"


def _splice_proof_states(
    states: dict[str, StateConfig],
    targets: list[str],
    execute_state: str,
    next_state: str,
    guard: str | None = None,
) -> None:
    """Insert one `check_proof_<slug>` per *target*, chained on_yes, rewiring `execute.next`.

    Mirrors skills/create-eval-from-issues/SKILL.md:306-327 (Variant A) / :406-422
    (Variant B). *guard* is an optional bash conditional prefix (Variant B only)
    so a shared proof state no-ops for issues that didn't declare the target.
    """
    if not targets:
        return

    proof_names = [_proof_state_name(t) for t in targets]
    for i, (target, name) in enumerate(zip(targets, proof_names, strict=True)):
        on_yes = proof_names[i + 1] if i + 1 < len(proof_names) else next_state
        cmd = f'll-learning-tests check --stale-aware "{target}"'
        action = f"{guard} && {cmd} || exit 0\n" if guard else f"{cmd}\n"
        states[name] = StateConfig(
            action=action,
            action_type="shell",
            evaluate=EvaluateConfig(type="exit_code"),
            on_yes=on_yes,
            on_no="done",
            on_error="done",
        )

    states[execute_state].next = proof_names[0]


def _variant_a(
    issue_id: str, info: IssueInfo, lt_enabled: bool
) -> tuple[dict[str, StateConfig], str]:
    states: dict[str, StateConfig] = {
        "execute": StateConfig(
            action=_EXECUTE_PLACEHOLDER,
            action_type="prompt",
            timeout=300,
            next="check_skill",
        ),
        "check_skill": StateConfig(
            action="Evaluate the feature from a real user's perspective.",
            action_type="prompt",
            timeout=180,
            evaluate=EvaluateConfig(type="llm_structured", prompt=_CRITERIA_PLACEHOLDER),
            on_yes="done",
            on_no="execute",
            on_partial="execute",
        ),
        "done": StateConfig(terminal=True),
    }

    targets = list(info.learning_tests_required or []) if lt_enabled else []
    _splice_proof_states(states, targets, "execute", "check_skill")

    description = (
        f"Eval harness for {issue_id}: {info.title}.\n"
        "Exercises the feature as a real user would and evaluates the quality of the "
        "experience.\n"
        "Generated by `ll-loop scaffold-eval`."
    )
    return states, description


def _variant_b(
    issue_ids: list[str], infos: list[IssueInfo], lt_enabled: bool
) -> tuple[dict[str, StateConfig], str]:
    quoted_ids = ", ".join(f"'{i}'" for i in issue_ids)
    discover_action = (
        'python3 -c "\n'
        "import sys\n"
        f"ids = [{quoted_ids}]\n"
        "pf = '${context.run_dir}/processed.txt'\n"
        "try:\n"
        "    processed = open(pf).read().split()\n"
        "except FileNotFoundError:\n"
        "    processed = []\n"
        "remaining = [i for i in ids if i not in processed]\n"
        "if not remaining:\n"
        "    sys.exit(1)\n"
        "print(remaining[0])\n"
        '"\n'
    )
    states: dict[str, StateConfig] = {
        "discover": StateConfig(
            action=discover_action,
            action_type="shell",
            evaluate=EvaluateConfig(type="exit_code"),
            capture="current_item",
            on_yes="execute",
            on_no="done",
            on_error="done",
        ),
        "execute": StateConfig(
            action=(
                f"{_EXECUTE_PLACEHOLDER}\n\n"
                "The current issue being evaluated is: ${captured.current_item.output}"
            ),
            action_type="prompt",
            timeout=300,
            max_retries=3,
            on_retry_exhausted="advance",
            next="check_skill",
        ),
        "check_skill": StateConfig(
            action=(
                "Evaluate the feature described in issue "
                "${captured.current_item.output} from a real user's perspective."
            ),
            action_type="prompt",
            timeout=180,
            evaluate=EvaluateConfig(
                type="llm_structured",
                prompt=(
                    f"{_CRITERIA_PLACEHOLDER}\n\n"
                    "The issue being evaluated is: ${captured.current_item.output}"
                ),
            ),
            on_yes="advance",
            on_no="execute",
            on_partial="execute",
        ),
        "advance": StateConfig(
            action='echo "${captured.current_item.output}" >> "${context.run_dir}/processed.txt"\n',
            action_type="shell",
            next="discover",
        ),
        "done": StateConfig(terminal=True),
    }

    # Union of every issue's learning_tests_required targets; each proof state is
    # guarded so it only runs `ll-learning-tests check` for the issue(s) that
    # declared that target (skills/create-eval-from-issues/SKILL.md:406-422).
    target_to_ids: dict[str, list[str]] = {}
    if lt_enabled:
        for issue_id, info in zip(issue_ids, infos, strict=True):
            for target in info.learning_tests_required or []:
                target_to_ids.setdefault(target, []).append(issue_id)

    if target_to_ids:
        proof_names = [_proof_state_name(t) for t in target_to_ids]
        for i, (target, ids) in enumerate(target_to_ids.items()):
            on_yes = proof_names[i + 1] if i + 1 < len(proof_names) else "check_skill"
            guard = " || ".join(f'[ "${{captured.current_item.output}}" = "{iid}" ]' for iid in ids)
            cmd = f'll-learning-tests check --stale-aware "{target}"'
            states[proof_names[i]] = StateConfig(
                action=f"({guard}) && {cmd} || exit 0\n",
                action_type="shell",
                evaluate=EvaluateConfig(type="exit_code"),
                on_yes=on_yes,
                on_no="done",
                on_error="done",
            )
        states["execute"].next = proof_names[0]

    titles = "; ".join(f"{i}: {info.title}" for i, info in zip(issue_ids, infos, strict=True))
    description = (
        f"Eval harness for {titles}: multi-item user-perspective evaluation.\n"
        "Exercises each feature as a real user would and evaluates the quality of the "
        "experience.\n"
        "Generated by `ll-loop scaffold-eval`."
    )
    return states, description


def scaffold_eval(issue_ids: list[str], dsl: bool) -> ScaffoldResult:
    """Generate an eval-harness loop for *issue_ids* (Variant A for 1, Variant B for 2+).

    ``dsl=True`` maps to the skill's separate DSL fill-in-the-blank/transform task
    generator (skills/create-eval-from-issues/SKILL.md's "DSL Mode" section) — a
    distinct, already-prose-only code path unrelated to FSM YAML templating. That
    generation logic is out of scope here; ``--dsl`` is rejected with a clear
    pointer back to the interactive skill flow rather than silently no-opping.
    """
    if dsl:
        return ScaffoldResult(
            yaml_path=None,
            yaml_text="",
            placeholders=[],
            validated=False,
            errors=[
                "--dsl is not implemented in ll-loop scaffold-eval. DSL task generation "
                "is a separate fill-in-the-blank/transform/correction pipeline, not FSM "
                "YAML templating — use `/ll:create-eval-from-issues --dsl <source>` instead."
            ],
        )

    if not issue_ids:
        return ScaffoldResult(
            yaml_path=None,
            yaml_text="",
            placeholders=[],
            validated=False,
            errors=["At least one issue ID is required."],
        )

    infos: list[IssueInfo] = []
    for issue_id in issue_ids:
        _, info, error = resolve_issue(issue_id)
        if error or info is None:
            return ScaffoldResult(
                yaml_path=None, yaml_text="", placeholders=[], validated=False, errors=[error or ""]
            )
        infos.append(info)

    lt_enabled = _learning_tests_enabled()
    slug = "-".join(i.lower() for i in issue_ids)
    name = f"eval-harness-{slug}"

    if len(issue_ids) == 1:
        states, description = _variant_a(issue_ids[0], infos[0], lt_enabled)
        timeout = _VARIANT_A_TIMEOUT
        max_steps = _VARIANT_A_MAX_STEPS
        initial = "execute"
    else:
        states, description = _variant_b(issue_ids, infos, lt_enabled)
        timeout = _VARIANT_B_TIMEOUT
        max_steps = _VARIANT_B_MAX_STEPS
        initial = "discover"

    fsm = FSMLoop(
        name=name,
        initial=initial,
        states=states,
        description=description,
        category="harness",
        max_steps=max_steps,
        timeout=timeout,
    )

    validation_errors = validate_fsm(fsm)
    has_errors = any(e.severity == ValidationSeverity.ERROR for e in validation_errors)
    yaml_text = dump_fsm_yaml(fsm)

    return ScaffoldResult(
        yaml_path=None,
        yaml_text=yaml_text,
        placeholders=[_EXECUTE_PLACEHOLDER, _CRITERIA_PLACEHOLDER],
        validated=not has_errors,
        errors=[f"{e.severity.value}: {e.path}: {e.message}" for e in validation_errors],
    )


def cmd_scaffold_eval(args: argparse.Namespace, loops_dir: Path) -> int:
    """Entry point for ``ll-loop scaffold-eval --issues A,B [--dsl] [--out|--stdout] [--json]``."""
    issue_ids = [i.strip() for i in (args.issues or "").split(",") if i.strip()]
    result = scaffold_eval(issue_ids, dsl=bool(getattr(args, "dsl", False)))

    out_path: Path | None = getattr(args, "out", None)
    if result.yaml_text and out_path is not None:
        atomic_write(out_path, result.yaml_text)
        result.yaml_path = out_path

    if getattr(args, "json", False):
        print_json(result.to_dict())
        return 0 if result.yaml_text else 1

    if not result.yaml_text:
        for err in result.errors:
            print(f"Error: {err}")
        return 1

    if getattr(args, "stdout", False) or out_path is None:
        print(result.yaml_text)

    if out_path is not None:
        print(f"Wrote: {out_path}")

    print(f"Validated: {'PASS' if result.validated else 'FAIL'}")
    print(f"Placeholders to fill: {', '.join(result.placeholders)}")
    for err in result.errors:
        print(f"  {err}")

    return 0 if result.validated else 1
